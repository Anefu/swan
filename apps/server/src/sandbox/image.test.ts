import { execFileSync } from "node:child_process";
import { mkdtempSync, readFileSync, writeFileSync } from "node:fs";
import os from "node:os";
import path from "node:path";
import { describe, expect, it } from "vitest";
import { SettingsSchema } from "../settings.js";
import { ADOPT_SCRIPT, adoptFiles, adoptKey, buildArgs, buildFiles, buildKey, setupScript, toolsScript } from "./image.js";

const mirrors = (m: object = {}) => SettingsSchema.parse({ mirrors: m }).mirrors;
const tools = (t: object = {}) => SettingsSchema.parse({ sandboxTools: t }).sandboxTools;
const NONE = tools();
const CERT = "-----BEGIN CERTIFICATE-----\nMIIBfake\n-----END CERTIFICATE-----";

const DEB822 = `Types: deb
URIs: http://deb.debian.org/debian
Suites: bookworm bookworm-updates

Types: deb
URIs: http://deb.debian.org/debian-security
Suites: bookworm-security
`;
const ONE_LINE = "deb http://deb.debian.org/debian bookworm main\ndeb http://deb.debian.org/debian-security bookworm-security main\n";

// The script runs in the Debian image, which has GNU sed; macOS's sed lacks \| and \?.
const gnuSed = (() => {
  try {
    return execFileSync("sed", ["--version"], { stdio: "pipe" }).toString().includes("GNU");
  } catch {
    return false;
  }
})();

describe("sandbox image setup", () => {
  it("changes nothing and keeps the image tag when nothing is configured", () => {
    const m = mirrors();
    const files = buildFiles(m, [], NONE);
    expect(files["swan/setup.sh"]).toBe("#!/bin/sh\n# Generated by Swan from config.yaml (mirrors, caFiles).\nset -eu\n");
    expect(files["swan/extra-ca.pem"]).toBe("");
    expect(files["swan-tools.sh"]).toBe("#!/bin/sh\n# Generated by Swan from config.yaml (sandboxTools).\nset -eu\ncd /tmp\n");
    expect(buildKey("FROM x", m, files, NONE)).toBeNull();
    expect(buildArgs(m)).toEqual([]);
  });

  it("points pip, uv and npm at the mirrors and passes the base image as a build argument", () => {
    const m = mirrors({ baseImage: "art.example.com/docker/library/node:22-bookworm-slim", pypi: "https://art.example.com/pypi/simple", npm: "https://art.example.com/npm/" });
    const script = setupScript(m, 0);
    expect(script).toContain("index-url = %s\\n' 'https://art.example.com/pypi/simple' > /etc/pip.conf");
    expect(script).toContain("/etc/uv/uv.toml");
    expect(script).toContain("'https://art.example.com/npm/' >> /usr/local/etc/npmrc");
    expect(buildArgs(m)).toEqual(["--build-arg", "BASE_IMAGE=art.example.com/docker/library/node:22-bookworm-slim"]);
  });

  it("sends the build's downloads through the proxy, reaching a proxy on this Mac from Podman's VM", () => {
    const args = (url: string) => buildArgs(mirrors(), SettingsSchema.parse({ proxy: { url, noProxy: [".corp.example.com"] } }).proxy);
    expect(args("http://proxy.corp.example.com:8080")).toEqual([
      "--http-proxy=false",
      "--build-arg", "HTTP_PROXY=http://proxy.corp.example.com:8080",
      "--build-arg", "HTTPS_PROXY=http://proxy.corp.example.com:8080",
      "--build-arg", "http_proxy=http://proxy.corp.example.com:8080",
      "--build-arg", "https_proxy=http://proxy.corp.example.com:8080",
      "--build-arg", "NO_PROXY=localhost,127.0.0.1,::1,.corp.example.com",
      "--build-arg", "no_proxy=localhost,127.0.0.1,::1,.corp.example.com",
    ]);
    expect(args("http://127.0.0.1:3128")[2]).toBe("HTTP_PROXY=http://host.containers.internal:3128");
    expect(args("http://localhost:3128/")[2]).toBe("HTTP_PROXY=http://host.containers.internal:3128/");
    expect(args("http://localhost.corp.example.com:3128")[2]).toBe("HTTP_PROXY=http://localhost.corp.example.com:3128");
  });

  it("adds extra certificates for apt's first download and for the system store", () => {
    const files = buildFiles(mirrors(), [CERT, CERT.replace("fake", "other")], NONE);
    expect(files["swan/ca/swan-extra-1.crt"]).toContain("MIIBfake");
    expect(files["swan/ca/swan-extra-2.crt"]).toContain("MIIBother");
    expect(files["swan/extra-ca.pem"]).toContain("MIIBother");
    expect(files["swan/setup.sh"]).toContain("Acquire::https::CAInfo");
    expect(files["swan/setup.sh"]).toContain("cp /tmp/swan/ca/*.crt /usr/local/share/ca-certificates/");
  });

  it("builds a new image when the mirrors or certificates change", () => {
    const a = mirrors({ pypi: "https://a.example.com/simple" });
    const b = mirrors({ pypi: "https://b.example.com/simple" });
    const key = (m: typeof a, cas: string[] = []) => buildKey("FROM x", m, buildFiles(m, cas, NONE), NONE);
    expect(key(a)).toMatch(/^[0-9a-f]{10}$/);
    expect(key(a)).toBe(key(a));
    expect(key(a)).not.toBe(key(b));
    expect(key(a)).not.toBe(key(a, [CERT]));
    expect(buildKey("FROM y", a, buildFiles(a, [], NONE), NONE)).not.toBe(key(a));
    expect(key(mirrors(), [CERT])).not.toBeNull();
  });

  it.runIf(gnuSed)("rewrites Debian sources in both formats, and only whole URLs", () => {
    const m = mirrors({
      apt: {
        "http://deb.debian.org/debian": "https://art.example.com/artifactory/debian-remote",
        "http://deb.debian.org/debian-security": "https://art.example.com/artifactory/debian-security-remote",
      },
    });
    const dir = mkdtempSync(path.join(os.tmpdir(), "swan-apt-"));
    const sed = setupScript(m, 0).split("\n").find((l) => l.startsWith("for f in"))!.match(/sed -i (.*) "\$f"/)![1]!;
    for (const [name, text] of [["debian.sources", DEB822], ["sources.list", ONE_LINE]] as const) {
      const f = path.join(dir, name);
      writeFileSync(f, text);
      execFileSync("sh", ["-c", `sed -i ${sed} "${f}"`]);
      const out = readFileSync(f, "utf8");
      expect(out).toContain("https://art.example.com/artifactory/debian-remote");
      expect(out).toContain("https://art.example.com/artifactory/debian-security-remote");
      expect(out).not.toContain("deb.debian.org");
    }
  });
});

describe("sandbox tools", () => {
  const KUBECTL = 'curl -fsSLo /usr/local/bin/kubectl "https://dl.k8s.io/release/v1.31.2/bin/linux/$(dpkg --print-architecture)/kubectl"\nchmod +x /usr/local/bin/kubectl\n';

  it("installs the packages, then runs the install script in /tmp, stopping at the first error", () => {
    const script = toolsScript(tools({ packages: ["postgresql-client", "jq=1.6-2.1"], install: KUBECTL }));
    const lines = script.split("\n");
    expect(lines.slice(2, 4)).toEqual(["set -eu", "cd /tmp"]);
    expect(lines).toContain("  apt-get install -y --no-install-recommends postgresql-client jq=1.6-2.1");
    expect(lines).toContain("elif command -v apk >/dev/null 2>&1; then apk add --no-cache postgresql-client jq=1.6-2.1");
    expect(lines.indexOf("  rm -rf /var/lib/apt/lists/*")).toBeLessThan(lines.findIndex((l) => l.startsWith("curl")));
    expect(script.endsWith("chmod +x /usr/local/bin/kubectl\n")).toBe(true);
    execFileSync("sh", ["-n"], { input: script }); // valid shell
  });

  it("builds a new image when the tools change, and only then", () => {
    const key = (t: typeof NONE) => buildKey("FROM x", mirrors(), buildFiles(mirrors(), [], t), t);
    expect(key(NONE)).toBeNull();
    expect(key(tools({ install: "  \n" }))).toBeNull();
    expect(key(tools({ packages: ["jq"] }))).toMatch(/^[0-9a-f]{10}$/);
    expect(key(tools({ install: KUBECTL }))).not.toBe(key(tools({ install: KUBECTL.replace("1.31.2", "1.32.0") })));
  });

  it("accepts only Debian package names, so nothing else runs through the package list", () => {
    for (const bad of ["jq; rm -rf /", "jq rm", "$(id)", "-y", "Jq"]) expect(() => tools({ packages: [bad] }), bad).toThrow(/Debian package/);
  });
});

describe("proxy settings", () => {
  it("refuses a proxy URL with a username and password", () => {
    expect(() => SettingsSchema.parse({ proxy: { url: "http://me:secret@proxy.corp.example.com:8080" } })).toThrow(/username and password/);
    expect(SettingsSchema.parse({ proxy: { url: "http://proxy.corp.example.com:8080" } }).proxy?.noProxy).toEqual([]);
  });
});

describe("mirror settings", () => {
  it("rejects values that could break out of the setup script", () => {
    for (const bad of ["https://x.example.com/a'b", "https://x.example.com/a b", "https://x.example.com/#frag", "ftp://x.example.com/", "https://x.example.com/$(id)"])
      expect(() => mirrors({ pypi: bad })).toThrow();
    expect(() => mirrors({ baseImage: "node:22; rm -rf /" })).toThrow();
    expect(() => mirrors({ apt: { "http://deb.debian.org/debian": "https://x.example.com/`id`" } })).toThrow();
  });
});

describe("a persona's own image", () => {
  it("is valid shell that checks for what the sandbox needs and adds Swan's certificates", () => {
    execFileSync("sh", ["-n"], { input: ADOPT_SCRIPT });
    expect(ADOPT_SCRIPT).toContain("for c in bash sleep cat awk mkdir chown");
    expect(ADOPT_SCRIPT).toContain("cat /tmp/swan/harness-ca.crt /tmp/swan/extra-ca.pem >> \"$bundle\"");
    const files = adoptFiles([CERT], tools({ packages: ["jq"] }));
    expect(Object.keys(files).sort()).toEqual(["swan-tools.sh", "swan/adopt.sh", "swan/extra-ca.pem"]);
    expect(files["swan/extra-ca.pem"]).toContain("MIIBfake");
  });

  it("builds again when the image, Swan's layer or the tools change", () => {
    const key = (base: string, t = NONE, cf = "FROM x") => adoptKey(cf, base, adoptFiles([], t));
    expect(key("reg.example.com/dev:1")).toBe(key("reg.example.com/dev:1"));
    expect(key("reg.example.com/dev:1")).not.toBe(key("reg.example.com/dev:2"));
    expect(key("reg.example.com/dev:1")).not.toBe(key("reg.example.com/dev:1", tools({ packages: ["jq"] })));
    expect(key("reg.example.com/dev:1")).not.toBe(key("reg.example.com/dev:1", NONE, "FROM y"));
  });
});
