import { createHash } from "node:crypto";
import { noProxyList } from "../network.js";
import type { Settings } from "../settings.js";

type Mirrors = Settings["mirrors"];
type Tools = Settings["sandboxTools"];

const quote = (s: string) => `'${s}'`; // settings.ts rejects quotes, spaces, #, $ and backslashes in these values
const regex = (s: string) => s.replace(/[.[\]*^$/]/g, "\\$&");
const replacement = (s: string) => s.replace(/[&/]/g, "\\$&");

/**
 * The script the Containerfile runs as root before its first download. It points apt, pip, uv and
 * npm at the mirrors and adds the extra root certificates. With nothing configured it does nothing.
 */
export function setupScript(m: Mirrors, extraCaCount: number): string {
  const lines = ["#!/bin/sh", "# Generated by Swan from config.yaml (mirrors, caFiles).", "set -eu"];
  const apt = Object.entries(m.apt);
  if (apt.length) {
    // Whole-word matches, for both deb822 (URIs:) and one-line sources.
    const exprs = apt.map(([from, to]) => `-e 's#\\(^\\|[[:space:]]\\)${regex(from)}/\\?\\([[:space:]]\\|$\\)#\\1${replacement(to)}\\2#g'`);
    lines.push(`for f in /etc/apt/sources.list.d/*.sources /etc/apt/sources.list; do [ -f "$f" ] && sed -i ${exprs.join(" ")} "$f"; done`);
  }
  if (apt.length || extraCaCount) {
    // The base image has no CA bundle yet: give apt Node's bundled roots plus the extra ones until ca-certificates is installed.
    // Only where there is apt: a persona's own image may be Alpine or Fedora.
    lines.push(
      "if [ -d /etc/apt/apt.conf.d ]; then",
      "mkdir -p /usr/local/share/swan",
      `if command -v node >/dev/null 2>&1; then node -e 'process.stdout.write(require("tls").rootCertificates.join("\\n") + "\\n")' > /usr/local/share/swan/bootstrap-ca.pem; fi`,
      "cat /tmp/swan/extra-ca.pem >> /usr/local/share/swan/bootstrap-ca.pem",
      `echo 'Acquire::https::CAInfo "/usr/local/share/swan/bootstrap-ca.pem";' > /etc/apt/apt.conf.d/90swan-bootstrap-ca`,
      "fi",
    );
  }
  if (extraCaCount) lines.push("mkdir -p /usr/local/share/ca-certificates", "cp /tmp/swan/ca/*.crt /usr/local/share/ca-certificates/");
  if (m.pypi) {
    lines.push(
      `printf '[global]\\nindex-url = %s\\n' ${quote(m.pypi)} > /etc/pip.conf`,
      `mkdir -p /etc/uv && printf '[[index]]\\nurl = "%s"\\ndefault = true\\n' ${quote(m.pypi)} > /etc/uv/uv.toml`,
    );
  }
  if (m.npm) lines.push(`mkdir -p /usr/local/etc && printf 'registry=%s\\n' ${quote(m.npm)} >> /usr/local/etc/npmrc`);
  return lines.join("\n") + "\n";
}

/**
 * The image's last step as root: config.yaml's sandboxTools, Debian packages and then the install
 * script, with the build's proxy, mirrors and certificates. With nothing configured it does nothing.
 */
export function toolsScript(t: Tools): string {
  const lines = ["#!/bin/sh", "# Generated by Swan from config.yaml (sandboxTools).", "set -eu", "cd /tmp"];
  const p = t.packages.join(" ");
  // Swan's image is Debian; a persona's own image may use another package manager.
  if (t.packages.length)
    lines.push(
      "if command -v apt-get >/dev/null 2>&1; then",
      "  apt-get update --error-on=any",
      `  apt-get install -y --no-install-recommends ${p}`,
      "  rm -rf /var/lib/apt/lists/*",
      `elif command -v apk >/dev/null 2>&1; then apk add --no-cache ${p}`,
      `elif command -v dnf >/dev/null 2>&1; then dnf install -y ${p} && dnf clean all`,
      `elif command -v microdnf >/dev/null 2>&1; then microdnf install -y ${p} && microdnf clean all`,
      `else echo "Swan: sandboxTools.packages needs apt-get, apk or dnf in the image" >&2; exit 1`,
      "fi",
    );
  if (t.install?.trim()) lines.push("# sandboxTools.install", t.install.trim());
  return lines.join("\n") + "\n";
}

const hasTools = (t: Tools) => t.packages.length > 0 || !!t.install?.trim();

/** The files Swan adds to the build context: swan/ for the first step, swan-tools.sh for the last. */
export function buildFiles(m: Mirrors, extraCas: string[], tools: Tools): Record<string, string> {
  const files: Record<string, string> = {
    "swan/setup.sh": setupScript(m, extraCas.length),
    "swan/extra-ca.pem": extraCas.length ? extraCas.join("\n") + "\n" : "",
    "swan-tools.sh": toolsScript(tools),
  };
  extraCas.forEach((pem, i) => (files[`swan/ca/swan-extra-${i + 1}.crt`] = pem + "\n"));
  return files;
}

/**
 * Build arguments: the base image, and the upstream proxy for the build's downloads (apt, pip).
 * Proxy variables are predefined build arguments, so RUN steps see them but the image does not keep
 * them. A proxy on this Mac's loopback is reached from Podman's VM as host.containers.internal.
 */
/** The company proxy as Podman's machine and builds reach it: a proxy on this Mac's loopback is the host to them. */
export function proxyEnv(proxy: Settings["proxy"]): Record<string, string> {
  if (!proxy) return {};
  const url = proxy.url.replace(/^(https?:\/\/)(localhost|127\.0\.0\.1|\[::1\])(?=[:/]|$)/i, "$1host.containers.internal");
  const noProxy = noProxyList(proxy).join(",");
  return { HTTP_PROXY: url, HTTPS_PROXY: url, http_proxy: url, https_proxy: url, NO_PROXY: noProxy, no_proxy: noProxy };
}

export function buildArgs(m: Mirrors, proxy?: Settings["proxy"]): string[] {
  const args = m.baseImage ? ["--build-arg", `BASE_IMAGE=${m.baseImage}`] : [];
  if (!proxy) return args;
  const env = proxyEnv(proxy);
  const url = env.HTTP_PROXY!;
  const noProxy = env.NO_PROXY!;
  // Only this proxy: Podman would otherwise also pass in the proxy variables of Swan's own (the shell's) environment.
  args.push("--http-proxy=false");
  for (const k of ["HTTP_PROXY", "HTTPS_PROXY", "http_proxy", "https_proxy"]) args.push("--build-arg", `${k}=${url}`);
  args.push("--build-arg", `NO_PROXY=${noProxy}`, "--build-arg", `no_proxy=${noProxy}`);
  return args;
}

/**
 * Adapts a persona's own image to the sandbox (Containerfile.base), in plain sh for any Linux: checks
 * what Swan needs, makes a uid 1000 user with a home, and adds Swan's certificate and caFiles to
 * the system store where there is one and to a bundle the certificate variables point to.
 */
export const ADOPT_SCRIPT = `#!/bin/sh
# Generated by Swan: adapts an image of your own to the sandbox.
set -eu
missing=""
for c in bash sleep cat awk mkdir chown; do command -v "$c" >/dev/null 2>&1 || missing="$missing $c"; done
if [ -n "$missing" ]; then
  echo "Swan: this image lacks$missing. The sandbox needs bash and the usual coreutils; add them to the image." >&2
  exit 1
fi

# Swan runs everything as 1000:1000: give that uid a name and a home.
user=$(awk -F: '$3 == 1000 { print $1; exit }' /etc/passwd)
if [ -z "$user" ]; then
  if ! awk -F: '$3 == 1000 { f = 1 } END { exit !f }' /etc/group; then
    if command -v groupadd >/dev/null 2>&1; then groupadd -g 1000 agent
    elif command -v addgroup >/dev/null 2>&1; then addgroup -g 1000 agent
    else echo "agent:x:1000:" >> /etc/group; fi
  fi
  group=$(awk -F: '$3 == 1000 { print $1; exit }' /etc/group)
  if command -v useradd >/dev/null 2>&1; then useradd -u 1000 -g 1000 -m -d /home/agent -s /bin/bash agent
  elif command -v adduser >/dev/null 2>&1; then adduser -D -u 1000 -G "$group" -h /home/agent -s /bin/bash agent
  else echo "agent:x:1000:1000::/home/agent:/bin/bash" >> /etc/passwd; fi
  user=agent
fi
home=$(awk -F: -v u="$user" '$1 == u { print $6; exit }' /etc/passwd)
mkdir -p "$home" /workspace /skills
chown 1000:1000 "$home" /workspace

# A minimal image may have no root certificates (Ubuntu's has none): install the usual store.
if ! [ -f /etc/ssl/certs/ca-certificates.crt ] && ! [ -f /etc/pki/tls/certs/ca-bundle.crt ] && ! [ -f /etc/ssl/cert.pem ]; then
  if command -v apt-get >/dev/null 2>&1; then
    apt-get update && apt-get install -y --no-install-recommends ca-certificates && rm -rf /var/lib/apt/lists/*
  elif command -v apk >/dev/null 2>&1; then apk add --no-cache ca-certificates
  elif command -v dnf >/dev/null 2>&1; then dnf install -y ca-certificates && dnf clean all
  else echo "Swan: this image has no root certificates and no apt-get, apk or dnf to add them; HTTPS to public hosts will fail." >&2; fi
fi

# Swan's certificate (for hosts it adds credentials to) and caFiles.
mkdir -p /usr/local/share/swan
bundle=/usr/local/share/swan/ca-bundle.pem
: > "$bundle"
for f in /etc/ssl/certs/ca-certificates.crt /etc/pki/tls/certs/ca-bundle.crt /etc/ssl/cert.pem; do
  if [ -f "$f" ]; then cat "$f" >> "$bundle"; break; fi
done
cat /tmp/swan/harness-ca.crt /tmp/swan/extra-ca.pem >> "$bundle"
if command -v update-ca-certificates >/dev/null 2>&1 && [ -d /usr/local/share/ca-certificates ]; then
  cp /tmp/swan/harness-ca.crt /usr/local/share/ca-certificates/swan-harness.crt
  if [ -s /tmp/swan/extra-ca.pem ]; then cp /tmp/swan/extra-ca.pem /usr/local/share/ca-certificates/swan-extra.crt; fi
  update-ca-certificates >/dev/null 2>&1 || true
elif command -v update-ca-trust >/dev/null 2>&1 && [ -d /etc/pki/ca-trust/source/anchors ]; then
  cp /tmp/swan/harness-ca.crt /etc/pki/ca-trust/source/anchors/swan-harness.crt
  if [ -s /tmp/swan/extra-ca.pem ]; then cp /tmp/swan/extra-ca.pem /etc/pki/ca-trust/source/anchors/swan-extra.crt; fi
  update-ca-trust extract || true
fi
if command -v git >/dev/null 2>&1; then git config --system safe.directory '*'; fi
`;

/** The build context for Swan's layer over a persona's own image. */
export function adoptFiles(extraCas: string[], tools: Tools, mirrors: Mirrors): Record<string, string> {
  return {
    "swan/setup.sh": setupScript(mirrors, 0), // the package mirrors; adopt.sh adds the certificates
    "swan/adopt.sh": ADOPT_SCRIPT,
    "swan/extra-ca.pem": extraCas.length ? extraCas.join("\n") + "\n" : "",
    "swan-tools.sh": toolsScript(tools),
  };
}

/** The tag part for a persona's own image: a new build when the image, Swan's layer or the tools change. */
export function adoptKey(containerfile: string, base: string, files: Record<string, string>): string {
  const h = createHash("sha256").update(containerfile).update(base);
  for (const k of Object.keys(files).sort()) h.update(k).update(files[k]!);
  return h.digest("hex").slice(0, 12);
}

/**
 * Part of the image tag, so changing the mirrors, certificates or tools builds a new image. Null
 * when none are configured, which keeps the tag (and the image already built) as before.
 */
export function buildKey(containerfile: string, m: Mirrors, files: Record<string, string>, tools: Tools): string | null {
  const configured = !!m.baseImage || !!m.pypi || !!m.npm || Object.keys(m.apt).length > 0 || files["swan/extra-ca.pem"] !== "" || hasTools(tools);
  if (!configured) return null;
  const h = createHash("sha256").update(containerfile).update(JSON.stringify(m));
  for (const k of Object.keys(files).sort()) h.update(k).update(files[k]!);
  return h.digest("hex").slice(0, 10);
}
